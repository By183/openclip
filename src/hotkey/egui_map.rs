use eframe::egui::{Key, Modifiers};

/// Maps an egui `Key` to a Windows Virtual-Key code (VK).
pub fn egui_key_to_vk(key: Key) -> Option<u32> {
    match key {
        Key::A => Some(0x41),
        Key::B => Some(0x42),
        Key::C => Some(0x43),
        Key::D => Some(0x44),
        Key::E => Some(0x45),
        Key::F => Some(0x46),
        Key::G => Some(0x47),
        Key::H => Some(0x48),
        Key::I => Some(0x49),
        Key::J => Some(0x4A),
        Key::K => Some(0x4B),
        Key::L => Some(0x4C),
        Key::M => Some(0x4D),
        Key::N => Some(0x4E),
        Key::O => Some(0x4F),
        Key::P => Some(0x50),
        Key::Q => Some(0x51),
        Key::R => Some(0x52),
        Key::S => Some(0x53),
        Key::T => Some(0x54),
        Key::U => Some(0x55),
        Key::V => Some(0x56),
        Key::W => Some(0x57),
        Key::X => Some(0x58),
        Key::Y => Some(0x59),
        Key::Z => Some(0x5A),
        Key::Num0 => Some(0x30),
        Key::Num1 => Some(0x31),
        Key::Num2 => Some(0x32),
        Key::Num3 => Some(0x33),
        Key::Num4 => Some(0x34),
        Key::Num5 => Some(0x35),
        Key::Num6 => Some(0x36),
        Key::Num7 => Some(0x37),
        Key::Num8 => Some(0x38),
        Key::Num9 => Some(0x39),
        Key::F1 => Some(0x70),
        Key::F2 => Some(0x71),
        Key::F3 => Some(0x72),
        Key::F4 => Some(0x73),
        Key::F5 => Some(0x74),
        Key::F6 => Some(0x75),
        Key::F7 => Some(0x76),
        Key::F8 => Some(0x77),
        Key::F9 => Some(0x78),
        Key::F10 => Some(0x79),
        Key::F11 => Some(0x7A),
        Key::F12 => Some(0x7B),
        Key::F13 => Some(0x7C),
        Key::F14 => Some(0x7D),
        Key::F15 => Some(0x7E),
        Key::F16 => Some(0x7F),
        Key::F17 => Some(0x80),
        Key::F18 => Some(0x81),
        Key::F19 => Some(0x82),
        Key::F20 => Some(0x83),
        Key::Space => Some(0x20),
        Key::Enter => Some(0x0D),
        Key::Tab => Some(0x09),
        Key::Backspace => Some(0x08),
        Key::Insert => Some(0x2D),
        Key::Delete => Some(0x2E),
        Key::Home => Some(0x24),
        Key::End => Some(0x23),
        Key::PageUp => Some(0x21),
        Key::PageDown => Some(0x22),
        Key::ArrowLeft => Some(0x25),
        Key::ArrowUp => Some(0x26),
        Key::ArrowRight => Some(0x27),
        Key::ArrowDown => Some(0x28),
        Key::Minus => Some(0xBD),
        Key::Equals | Key::Plus => Some(0xBB),
        Key::OpenBracket => Some(0xDB),
        Key::CloseBracket => Some(0xDD),
        Key::Backslash => Some(0xDC),
        Key::Semicolon => Some(0xBA),
        Key::Quote => Some(0xDE),
        Key::Comma => Some(0xBC),
        Key::Period => Some(0xBE),
        Key::Slash => Some(0xBF),
        Key::Backtick => Some(0xC0),
        _ => None,
    }
}

/// Helper to convert modifiers + key into a HotkeyConfig.
pub fn from_egui(modifiers: Modifiers, key: Key, sound: bool) -> Option<super::HotkeyConfig> {
    if key == Key::Escape {
        return None;
    }
    let vk = egui_key_to_vk(key)?;
    Some(super::HotkeyConfig {
        enabled: true,
        ctrl: modifiers.ctrl,
        alt: modifiers.alt,
        shift: modifiers.shift,
        win: modifiers.mac_cmd,
        vk,
        sound,
    })
}
